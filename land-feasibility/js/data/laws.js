  TD.data.lawLink = function (name) {
    var k, e;
    for (k in TD.data.laws) {
      if (!Object.prototype.hasOwnProperty.call(TD.data.laws, k) || k.charAt(0) === '_') continue;
      e = TD.data.laws[k];
      if (e && e.url && name && String(name).indexOf(e.name.replace(/ 第.*$/, '')) === 0) return e.url;
    }
    return MOJ_HOME;
  };

